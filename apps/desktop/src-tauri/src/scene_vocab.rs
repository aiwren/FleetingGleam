/// Pictures that look like something else than a place; see the module note.
pub const DISTRACTORS: &[&str] = &[
    "a bouquet of flowers held in hands",
    "a close-up portrait of a person's face",
    "a group selfie",
    "a plate of food close-up",
    "a pet dog or cat",
    "a car close-up",
    "a product photo on a table",
    "a screenshot or document",
    "a collage of several photos",
    "a cartoon or sticker illustration",
    "a person holding an umbrella",
    "a couple posing together",
    "a baby",
    "a hand holding a phone",
    "a drink cup close-up",
];

pub const DIM: usize = 512;
static TABLE: &[u8] = include_bytes!("scene_vocab_b32.bin");

fn rows() -> Vec<Vec<f32>> {
    TABLE.chunks_exact(DIM * 4).map(|r| r.chunks_exact(4).map(|c| f32::from_le_bytes([c[0], c[1], c[2], c[3]])).collect()).collect()
}

/// A place name for a scene.
pub struct Name {
    pub zh: &'static str,
    pub en: String,
}

/// The English name of an entry: its description without the article, capitalised.
pub fn english(desc: &str) -> String {
    let d = ["a ", "an ", "the "].iter().find_map(|a| desc.strip_prefix(a)).unwrap_or(desc);
    let mut c = d.chars();
    match c.next() { Some(f) => f.to_uppercase().collect::<String>() + c.as_str(), None => String::new() }
}

/// The group must hold at least this share of all the probability, and the best word this share of its group.
const MIN_GROUP: f32 = 0.45;
const MIN_WORD: f32 = 0.08;

/// The name of the place a scene shows, from the unit-length mean of its photos' ViT-B/32 embeddings; `None` when nothing fits clearly.
pub fn name(mean: &[f32]) -> Option<Name> {
    let table = rows();
    if mean.len() != DIM || table.len() != ENTRIES.len() + DISTRACTORS.len() {
        return None;
    }
    let logits: Vec<f32> = table.iter().map(|t| 100.0 * t.iter().zip(mean).map(|(a, b)| a * b).sum::<f32>()).collect();
    let max = logits.iter().cloned().fold(f32::MIN, f32::max);
    let exp: Vec<f32> = logits.iter().map(|l| (l - max).exp()).collect();
    let sum: f32 = exp.iter().sum();
    let p: Vec<f32> = exp.iter().map(|e| e / sum).collect();
    let (places, distractors) = p.split_at(ENTRIES.len());
    let mut mass = [0f32; 16];
    for (i, &(g, _, _)) in ENTRIES.iter().enumerate() {
        mass[g as usize] += places[i];
    }
    let (g, gm) = mass.iter().enumerate().max_by(|a, b| a.1.partial_cmp(b.1).unwrap()).map(|(g, m)| (g as u8, *m))?;
    if distractors.iter().sum::<f32>() > gm || gm < MIN_GROUP {
        return None;
    }
    let (i, pi) = ENTRIES.iter().enumerate().filter(|(_, e)| e.0 == g).map(|(i, _)| (i, places[i])).max_by(|a, b| a.1.partial_cmp(&b.1).unwrap())?;
    if pi / gm < MIN_WORD {
        return None;
    }
    Some(Name { zh: ENTRIES[i].2, en: english(ENTRIES[i].1) })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_matches_the_vocabulary() {
        assert_eq!(rows().len(), ENTRIES.len() + DISTRACTORS.len(), "regenerate scene_vocab_b32.bin: cargo test make_scene_vocab -- --ignored");
        assert!(ENTRIES.iter().all(|e| (e.0 as usize) < 16));
        assert_eq!(english("a green grass lawn"), "Green grass lawn");
    }

    /// Writes `scene_vocab_b32.bin` from the multilingual text model in `models/` (development only).
    #[test]
    #[ignore = "needs models/ with the search pack; rewrites scene_vocab_b32.bin"]
    fn make_scene_vocab() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../models");
        let enc = crate::textsearch::TextEncoder::load(&dir).expect("text model");
        let mut out: Vec<u8> = Vec::new();
        let descs = ENTRIES.iter().map(|e| e.1).chain(DISTRACTORS.iter().copied());
        for desc in descs {
            // Most photos have people in them whatever the place, so two of the prompts include people: that part is the same for
            // every word, and what tells the words apart is the place.
            let mut v = vec![0f32; DIM];
            for text in [format!("a photo of people at {desc}"), format!("a photo taken at {desc}"), desc.to_string()] {
                enc.encode(&text).unwrap().iter().zip(v.iter_mut()).for_each(|(x, y)| *y += x);
            }
            let n = v.iter().map(|x| x * x).sum::<f32>().sqrt();
            v.iter_mut().for_each(|x| *x /= n);
            v.iter().for_each(|x| out.extend_from_slice(&x.to_le_bytes()));
        }
        std::fs::write(std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/scene_vocab_b32.bin"), out).unwrap();
    }

    /// A sanity check on pictures that have nothing to do with how the words were chosen: the sample photos of the dev harness.
    #[test]
    #[ignore = "needs models/ (ViT-B/32 vision)"]
    fn name_dev_photos() {
        use crate::scorer::AiScorer;
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
        let scorer = crate::scorer::ClipScorer::load(&root.join("../models"), true, crate::scorer::Quality::Fast).expect("clip");
        let mut files: Vec<_> = std::fs::read_dir(root.join("../public/dev-photos")).unwrap().filter_map(|e| e.ok().map(|e| e.path())).collect();
        files.sort();
        for f in files {
            let emb = scorer.analyze(&image::open(&f).unwrap()).unwrap().embedding;
            println!("{}: {:?}", f.file_name().unwrap().to_string_lossy(), name(&emb).map(|n| (n.zh, n.en)));
        }
    }
}
